static const int *g_toks;
static size_t g_n, g_pos, g_over;

token_t getToken(FILE *stream)
{
    (void)stream;
    token_t t;
    memset(&t, 0, sizeof t);

    if (g_pos < g_n) {
        t.type = g_toks[g_pos++];
    } else {
        t.type = TKN_EOF;
        g_over++;
    }

    if (t.type == TKN_ID) {
        char *buf = malloc(32);
        if (buf) {
            snprintf(buf, 32, "id_%zu", g_pos);
            t.string = buf;
        }
    } else if (t.type == TKN_STRING || t.type == TKN_MULTILINE_STRING) {
        char *buf = malloc(8);
        if (buf) {
            strcpy(buf, "str");
            t.string = buf;
        }
    }

    return t;
}

/* ------------------------------------------------------------------ */
/* Zastupna funkce za precedencni analyzu                              */
/* ------------------------------------------------------------------ */

static int is_operand(int t)
{
    return t == TKN_ID ||
           t == TKN_INT ||
           t == TKN_DOUBLE ||
           t == TKN_STRING ||
           t == TKN_MULTILINE_STRING ||
           t == TKN_UNIT;
}

static int is_binop(int t)
{
    switch (t) {
        case TKN_PLUS:
        case TKN_MINUS:
        case TKN_TIMES:
        case TKN_DIVISION_SLASH:
        case TKN_EQUAL:
        case TKN_NOT_EQUAL:
        case TKN_LESS:
        case TKN_LESS_EQUAL:
        case TKN_GREATER:
        case TKN_GREATER_EQUAL:
            return 1;
        default:
            return 0;
    }
}

void parser_expretion(FILE *stream, token_t *token)
{
    int expect_operand = 1, depth = 0, prev_id = 0, just_opened = 0;
    int is_call[64];

    for (;;) {
        int t = token->type;
        if (is_operand(t)) {
            if (!expect_operand) exit(2);
            expect_operand = 0;
            prev_id = (t == TKN_ID);
            just_opened = 0;
        } else if (t == TKN_OPENING_PARENTHESES) {
            if (depth >= 63) exit(2);
            if (expect_operand) {
                is_call[depth++] = 0;
            } else if (prev_id) {
                is_call[depth++] = 1;
                expect_operand = 1;
            } else {
                exit(2);
            }
            just_opened = 1;
            prev_id = 0;
        } else if (t == TKN_CLOSING_PARENTHESES) {
            if (depth == 0) break;
            if (expect_operand && !(is_call[depth - 1] && just_opened)) exit(2);
            depth--;
            expect_operand = 0;
            prev_id = 0;
            just_opened = 0;
        } else if (t == TKN_COMMA && depth > 0 && is_call[depth - 1]) {
            if (expect_operand) exit(2);
            expect_operand = 1;
            prev_id = 0;
            just_opened = 0;
        } else if (is_binop(t)) {
            if (expect_operand) {
                if (t != TKN_MINUS && t != TKN_PLUS) exit(2);
            } else {
                expect_operand = 1;
            }
            prev_id = 0;
            just_opened = 0;
        } else {
            break;
        }
        *token = getToken(stream);
    }
    if (expect_operand) exit(2);
    if (depth != 0) exit(2);
}

